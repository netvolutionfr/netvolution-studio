// Development persistence adapter (ADR-0004, ADR-0008): projects, media and
// export over HTTP, served by the Vite dev/preview server on 127.0.0.1 only.
// Not a production backend.
import { execFile, spawn } from 'node:child_process';
import { createHash, randomBytes } from 'node:crypto';
import { copyFile, cp, mkdir, readdir, readFile, rename, stat, writeFile } from 'node:fs/promises';
import type { IncomingMessage, ServerResponse } from 'node:http';
import { join, resolve, sep } from 'node:path';
import { promisify } from 'node:util';
import { registry } from '@ns/components/definitions';
import {
  AiError,
  type Asset,
  aiRequestSchema,
  checkSite,
  commandCatalog,
  issueMessage,
  loadSite,
  MEDIA_PATH,
  type Message,
  msg,
  type Site,
  serializeSite,
} from '@ns/core';
import { exportProject } from '../../../packages/export-astro/src/write.ts';
import { type AiConfig, createAiService } from './ai/service.ts';
import { checkSvg, cleanName, EXT_TYPE, guessFont, MAX_UPLOAD, MEDIA_FILE, MEDIA_TYPES } from './media.ts';

export type ApiOptions = {
  /** Projects: <dataDir>/projects/<id>/{site.json,media/}; deleted projects: <dataDir>/trash/. */
  dataDir: string;
  /** Read-only media sources (e.g. fixtures/media), copied into a project created from a template. */
  mediaDirs?: string[];
  /** Built-in site templates (project archives, read-only); the user's are in <dataDir>/templates/. */
  templatesDir?: string;
  /** AI assistant (ADR-0014): provider and limits; disabled when absent. Keys never leave the server. */
  ai?: AiConfig;
  exportsDir: string;
  /** Font catalog (ADR-0018): `catalog.json`, `files/*.woff2`; no catalog when absent. */
  fontsDir?: string;
};

type CatalogFont = {
  id: string;
  family: string;
  category: string;
  license: string;
  files: { file: string; weight: { min: number; max: number }; style: 'normal' | 'italic' }[];
};

/** Project ids are generated by the server (ADR-0008); `p` + 10 characters. */
const PROJECT_ID = /^p[a-z0-9]{10}$/;
const MAX_DOC = 5 * 1024 * 1024;
const MAX_ARCHIVE = 200 * 1024 * 1024;
const ARCHIVE_FORMAT = 'ns.archive';
const TEMPLATE_ID = /^[a-z0-9][a-z0-9-]{0,63}$/;
/** Project archive (SB-12); site templates add their name and description (CS-02). */
type Archive = {
  format: string;
  version: number;
  site: unknown;
  media: Record<string, unknown>;
  template?: { name: string; description: string };
};
const run = promisify(execFile);

class HttpError extends Error {
  readonly status: number;
  readonly details: unknown;
  /** Sent to the Studio, which translates it (ADR-0024). */
  readonly detail: Message;
  constructor(status: number, detail: Message, details?: unknown) {
    super(detail.key);
    this.status = status;
    this.detail = detail;
    this.details = details;
  }
}

const etagOf = (content: string | Buffer) =>
  `"${createHash('sha256').update(content).digest('hex').slice(0, 32)}"`;

function inside(root: string, ...parts: string[]) {
  const base = resolve(root);
  const target = resolve(base, ...parts);
  if (!target.startsWith(base + sep)) throw new HttpError(400, msg('server.path'));
  return target;
}

async function atomicWrite(path: string, content: string | Buffer) {
  const tmp = `${path}.${randomBytes(6).toString('hex')}.tmp`;
  await writeFile(tmp, content);
  await rename(tmp, path);
}

async function body(req: IncomingMessage, limit: number): Promise<Buffer> {
  const chunks: Buffer[] = [];
  let size = 0;
  for await (const chunk of req) {
    size += (chunk as Buffer).length;
    if (size > limit) throw new HttpError(413, msg('server.tooLarge'));
    chunks.push(chunk as Buffer);
  }
  return Buffer.concat(chunks);
}

async function jsonBody(req: IncomingMessage, limit = MAX_DOC) {
  try {
    return JSON.parse((await body(req, limit)).toString('utf8')) as unknown;
  } catch (e) {
    throw e instanceof HttpError ? e : new HttpError(400, msg('server.json'));
  }
}

function validDocument(input: unknown) {
  const result = loadSite(input, registry);
  if (!result.ok) throw new HttpError(422, msg('server.invalidDocument'), result.diagnostics);
  return result.doc;
}

/**
 * Mutating requests must carry `X-NS-Request` (forces a CORS preflight that
 * foreign sites cannot pass) and, when present, a same-host `Origin`.
 */
function checkOrigin(req: IncomingMessage) {
  if (req.method === 'GET' || req.method === 'HEAD') return;
  if (req.headers['x-ns-request'] !== '1') throw new HttpError(403, msg('server.header'));
  const origin = req.headers.origin;
  if (origin && new URL(origin).host !== req.headers.host) throw new HttpError(403, msg('server.origin'));
}

const randomId = (prefix: string, length: number) =>
  `${prefix}${[...randomBytes(length)].map((b) => (b % 36).toString(36)).join('')}`;

export function createApi(options: ApiOptions) {
  const projectsDir = join(options.dataDir, 'projects');
  const trashDir = join(options.dataDir, 'trash');
  const ready = Promise.all([mkdir(projectsDir, { recursive: true }), mkdir(trashDir, { recursive: true })]);
  const projectDir = (id: string) => {
    if (!PROJECT_ID.test(id)) throw new HttpError(400, msg('server.projectId'));
    return inside(projectsDir, id);
  };
  const readSite = async (id: string) => {
    const content = await readFile(join(projectDir(id), 'site.json'), 'utf8').catch(() => null);
    if (content === null) throw new HttpError(404, msg('server.project'));
    return content;
  };
  const writeSite = async (dir: string, site: Site) => {
    const content = serializeSite(site);
    await atomicWrite(join(dir, 'site.json'), content);
    return etagOf(content);
  };
  const newProjectId = async () => {
    for (;;) {
      const id = randomId('p', 10);
      if (!(await stat(join(projectsDir, id)).catch(() => null))) return id;
    }
  };

  const ai = createAiService(
    options.ai ?? {
      provider: null,
      reason: msg('ai.errors.notConfigured'),
      maxTokens: 4000,
      perMinute: 10,
      dailyTokens: 200_000,
    },
  );
  const userTemplates = join(options.dataDir, 'templates');
  const templateDirs = (): [string, boolean][] => [
    ...(options.templatesDir ? ([[options.templatesDir, true]] as [string, boolean][]) : []),
    [userTemplates, false],
  ];
  const findTemplate = async (id: string) => {
    for (const [dir, builtIn] of templateDirs()) {
      const path = inside(dir, `${id}.json`);
      const content = await readFile(path, 'utf8').catch(() => null);
      if (content !== null) return { path, builtIn, archive: JSON.parse(content) as unknown };
    }
    throw new HttpError(404, msg('server.template'));
  };

  /** Source site and media files of a project (SB-12 archive, CS-02 template). */
  const archiveOf = async (id: string): Promise<Archive> => {
    const site = JSON.parse(await readSite(id)) as Site;
    const media: Record<string, string> = {};
    for (const asset of Object.values(site.assets)) {
      const content = await readFile(inside(projectDir(id), 'media', asset.file)).catch(() => null);
      if (content) media[asset.file] = content.toString('base64');
    }
    return { format: ARCHIVE_FORMAT, version: 1, site, media };
  };

  /** New project from an archive or template; every media file is checked like an upload. */
  const importArchive = async (input: unknown, name = '') => {
    const archive = input as Archive;
    if (archive?.format !== ARCHIVE_FORMAT || typeof archive.media !== 'object' || archive.media === null) {
      throw new HttpError(400, msg('server.archive'));
    }
    const id = await newProjectId();
    const site = { ...validDocument(archive.site), id, ...(name && { name }) };
    const dir = inside(projectsDir, id);
    await mkdir(join(dir, 'media'), { recursive: true });
    let missingMedia = 0;
    for (const asset of Object.values(site.assets)) {
      const type = MEDIA_TYPES[asset.mime];
      const data = archive.media[asset.file];
      const content = typeof data === 'string' ? Buffer.from(data, 'base64') : null;
      const valid =
        content &&
        type &&
        MEDIA_FILE.test(asset.file) &&
        asset.file.endsWith(`.${type.ext}`) &&
        content.length <= type.max &&
        (type.kind === 'svg' ? checkSvg(content.toString('utf8')) === null : type.sniff(content));
      if (!valid) {
        missingMedia++;
        continue;
      }
      await atomicWrite(inside(dir, 'media', asset.file), content);
    }
    const etag = await writeSite(dir, site);
    return { id, etag, missingMedia };
  };

  async function handle(req: IncomingMessage, res: ServerResponse): Promise<boolean> {
    const url = new URL(req.url ?? '/', 'http://local');
    const send = (status: number, data: unknown, headers: Record<string, string> = {}) => {
      res.writeHead(status, {
        'content-type': 'application/json; charset=utf-8',
        'cache-control': 'no-store',
        ...headers,
      });
      res.end(JSON.stringify(data));
    };

    // GET /media/<projectId>/<file>
    const media = new RegExp(`^${MEDIA_PATH}([^/]+)/([^/]+)$`).exec(url.pathname);
    if (media && req.method === 'GET') {
      const [, id, file] = media as unknown as [string, string, string];
      if (!MEDIA_FILE.test(file)) throw new HttpError(404, msg('server.media'));
      const content = await readFile(inside(projectDir(id), 'media', file)).catch(() => null);
      if (!content) throw new HttpError(404, msg('server.media'));
      const mime = EXT_TYPE[file.split('.').pop() as string] ?? 'application/octet-stream';
      const kind = MEDIA_TYPES[mime]?.kind;
      res.writeHead(200, {
        'content-type': mime,
        'x-content-type-options': 'nosniff',
        'cache-control': 'public, max-age=31536000, immutable',
        // Opened directly, an SVG may not load or run anything; files are always downloaded.
        ...(kind === 'svg' && { 'content-security-policy': "default-src 'none'; style-src 'unsafe-inline'" }),
        ...(kind === 'file' && { 'content-disposition': 'attachment' }),
      });
      res.end(content);
      return true;
    }
    if (!url.pathname.startsWith('/api/')) return false;
    checkOrigin(req);
    await ready;

    // POST /api/projects/import — an archive (GET …/archive): new project, every media file checked like an upload.
    if (url.pathname === '/api/projects/import' && req.method === 'POST') {
      const created = await importArchive(await jsonBody(req, MAX_ARCHIVE));
      send(201, created, { etag: created.etag });
      return true;
    }

    // AI assistant (ADR-0014): status (never a key) and completions within the limits.
    if (url.pathname === '/api/ai/status' && req.method === 'GET') {
      send(200, ai.status());
      return true;
    }
    if (url.pathname === '/api/ai/complete' && req.method === 'POST') {
      const parsed = aiRequestSchema.safeParse(await jsonBody(req));
      if (!parsed.success)
        throw new HttpError(
          400,
          msg('server.aiRequest', { detail: issueMessage(parsed.error.issues[0]?.message ?? '') }),
        );
      try {
        send(200, await ai.complete(parsed.data));
      } catch (error) {
        const e = error instanceof AiError ? error : new AiError('invalid-response', msg('server.aiError'));
        const statuses: Record<string, number> = {
          disabled: 503,
          'rate-limit': 429,
          budget: 429,
          auth: 502,
          refused: 422,
          timeout: 504,
        };
        throw new HttpError(statuses[e.code] ?? 502, e.detail, [{ code: e.code }]);
      }
      return true;
    }

    // Font catalog (ADR-0018): list, files for the previews, and copy into a project's media.
    const catalog = async (): Promise<CatalogFont[]> =>
      options.fontsDir
        ? JSON.parse(await readFile(join(options.fontsDir, 'catalog.json'), 'utf8').catch(() => '[]'))
        : [];
    if (url.pathname === '/api/fonts' && req.method === 'GET') {
      send(200, await catalog());
      return true;
    }
    const fontFile = /^\/api\/fonts\/files\/([a-z0-9-]+\.woff2)$/.exec(url.pathname);
    if (fontFile && req.method === 'GET' && options.fontsDir) {
      const content = await readFile(inside(options.fontsDir, 'files', fontFile[1] as string)).catch(
        () => null,
      );
      if (!content) throw new HttpError(404, msg('server.font'));
      res.writeHead(200, {
        'content-type': 'font/woff2',
        'x-content-type-options': 'nosniff',
        'cache-control': 'public, max-age=86400',
      });
      res.end(content);
      return true;
    }

    // GET /api/commands — catalog of the business commands as tools (CS-10, ADR-0013), MCP-shaped.
    if (url.pathname === '/api/commands' && req.method === 'GET') {
      send(200, commandCatalog());
      return true;
    }

    // Site templates (CS-02): built-in (read-only) and saved by the user, both project archives.
    if (url.pathname === '/api/templates' && req.method === 'GET') {
      const list = [];
      for (const [dir, builtIn] of templateDirs()) {
        for (const file of (await readdir(dir).catch(() => [])).filter((f) => f.endsWith('.json')).sort()) {
          const id = file.slice(0, -5);
          if (!TEMPLATE_ID.test(id)) continue;
          const archive = JSON.parse(await readFile(join(dir, file), 'utf8')) as Archive;
          const site = archive.site as Partial<Site> | undefined;
          list.push({
            id,
            builtIn,
            name: archive.template?.name ?? site?.name ?? id,
            description: archive.template?.description ?? '',
            pages: site?.pages?.length ?? 0,
          });
        }
      }
      send(200, list);
      return true;
    }
    const template = /^\/api\/templates\/([^/]+)(\/projects)?$/.exec(url.pathname);
    if (template) {
      const id = decodeURIComponent(template[1] as string);
      if (!TEMPLATE_ID.test(id)) throw new HttpError(400, msg('server.templateId'));
      const found = await findTemplate(id);
      // POST /api/templates/:id/projects { name? } — a new project from the template.
      if (template[2] && req.method === 'POST') {
        const { name } = (await jsonBody(req)) as { name?: unknown };
        const created = await importArchive(
          found.archive,
          typeof name === 'string' ? name.trim().slice(0, 200) : '',
        );
        send(201, created, { etag: created.etag });
        return true;
      }
      if (!template[2] && req.method === 'DELETE') {
        if (found.builtIn) throw new HttpError(403, msg('server.builtInTemplate'));
        await rename(found.path, inside(trashDir, `template-${id}-${Date.now()}.json`));
        send(200, {});
        return true;
      }
    }

    if (url.pathname === '/api/projects') {
      // GET /api/projects — most recently modified first.
      if (req.method === 'GET') {
        const list = [];
        for (const id of (await readdir(projectsDir)).filter((n) => PROJECT_ID.test(n))) {
          const path = join(projectsDir, id, 'site.json');
          const site = JSON.parse(await readFile(path, 'utf8').catch(() => 'null')) as Site | null;
          if (!site) continue;
          const updatedAt = (await stat(path)).mtime.toISOString();
          list.push({ id, name: site.name, pages: site.pages.length, updatedAt });
        }
        send(
          200,
          list.sort((a, b) => b.updatedAt.localeCompare(a.updatedAt)),
        );
        return true;
      }
      // POST /api/projects — body: a site (template or import, v1 accepted); the server assigns the id
      // and copies the referenced media found in the read-only sources.
      if (req.method === 'POST') {
        const id = await newProjectId();
        const site = { ...validDocument(await jsonBody(req)), id };
        const dir = inside(projectsDir, id);
        await mkdir(join(dir, 'media'), { recursive: true });
        let missingMedia = 0;
        for (const asset of Object.values(site.assets)) {
          const sources = (options.mediaDirs ?? []).map((d) => inside(d, asset.file));
          let copied = false;
          for (const src of sources) {
            if (
              await copyFile(src, inside(dir, 'media', asset.file)).then(
                () => true,
                () => false,
              )
            ) {
              copied = true;
              break;
            }
          }
          if (!copied) missingMedia++;
        }
        const etag = await writeSite(dir, site);
        send(201, { id, etag, missingMedia }, { etag });
        return true;
      }
    }

    // GET /api/exports/:name.tar.gz — an export (Astro sources or static site) as a compressed archive,
    // to retrieve it from a hosted Studio (ADR-0015); dependencies, build cache and build output excluded.
    const exported = /^\/api\/exports\/([a-z0-9]+-[0-9T-]{19}(-statique)?)\.tar\.gz$/.exec(url.pathname);
    if (exported && req.method === 'GET') {
      const name = exported[1] as string;
      if (!(await stat(inside(options.exportsDir, name)).catch(() => null))?.isDirectory())
        throw new HttpError(404, msg('server.export'));
      const excluded = ['node_modules', '.astro', ...(exported[2] ? [] : [`${name}/dist`])];
      const tar = spawn('tar', [
        '-czf',
        '-',
        ...excluded.map((e) => `--exclude=${e}`),
        '-C',
        options.exportsDir,
        name,
      ]);
      res.writeHead(200, {
        'content-type': 'application/gzip',
        'content-disposition': `attachment; filename="${name}.tar.gz"`,
        'cache-control': 'no-store',
      });
      tar.stdout.pipe(res);
      tar.on('error', () => res.destroy());
      tar.on('close', (code) => code !== 0 && res.destroy());
      return true;
    }

    const project = /^\/api\/projects\/([^/]+)(\/[a-z]+)?$/.exec(url.pathname);
    if (project) {
      const id = decodeURIComponent(project[1] as string);
      const dir = projectDir(id);
      const action = `${req.method} ${project[2] ?? ''}`;

      if (action === 'GET ') {
        const current = await readSite(id);
        send(200, JSON.parse(current), { etag: etagOf(current) });
        return true;
      }
      if (action === 'PUT ') {
        // Optimistic concurrency: update only the version last read (ETag).
        const ifMatch = req.headers['if-match'];
        if (!ifMatch) throw new HttpError(428, msg('server.ifMatch'));
        const current = await readSite(id);
        if (ifMatch !== etagOf(current)) {
          throw new HttpError(412, msg('server.conflict'));
        }
        const site = validDocument(await jsonBody(req));
        if (site.id !== id) throw new HttpError(400, msg('server.siteId'));
        const etag = await writeSite(dir, site);
        send(200, { etag }, { etag });
        return true;
      }
      // DELETE: moved to the trash, never erased from the Studio (ADR-0008).
      if (action === 'DELETE ') {
        await readSite(id);
        const stamp = new Date().toISOString().replace(/[:.]/g, '-').slice(0, 19);
        await rename(dir, inside(trashDir, `${id}-${stamp}`));
        send(200, {});
        return true;
      }
      if (action === 'POST /duplicate') {
        const site = JSON.parse(await readSite(id)) as Site;
        const copyId = await newProjectId();
        const copyDir = inside(projectsDir, copyId);
        await cp(dir, copyDir, { recursive: true });
        await writeSite(copyDir, { ...site, id: copyId, name: `${site.name} (copie)`.slice(0, 200) });
        send(201, { id: copyId });
        return true;
      }
      // POST /api/projects/:id/fonts { font } — a catalog font's files become media of the project.
      if (action === 'POST /fonts') {
        await readSite(id);
        const { font: fontId } = (await jsonBody(req)) as { font?: unknown };
        const font = (await catalog()).find((f) => f.id === fontId);
        if (!font || !options.fontsDir) throw new HttpError(404, msg('server.fontCatalog'));
        await mkdir(join(dir, 'media'), { recursive: true });
        const assets: Asset[] = [];
        for (const f of font.files) {
          const assetId = randomId('a', 10);
          const file = `${assetId}.woff2`;
          await atomicWrite(
            inside(dir, 'media', file),
            await readFile(inside(options.fontsDir, 'files', f.file)),
          );
          assets.push({
            id: assetId,
            file,
            name: f.file,
            kind: 'font',
            mime: 'font/woff2',
            size: (await stat(inside(dir, 'media', file))).size,
            family: font.family,
            weight: f.weight,
            style: f.style,
            license: font.license,
          });
        }
        send(201, assets);
        return true;
      }
      // GET /api/projects/:id/media — files present (missing-media detection).
      // With ?sizes, an object file → size in bytes (heavy background images, ADR-0017).
      if (action === 'GET /media') {
        await readSite(id);
        const files = (await readdir(join(dir, 'media')).catch(() => [])).filter((f) => MEDIA_FILE.test(f));
        if (!url.searchParams.has('sizes')) send(200, files);
        else {
          const sizes: Record<string, number> = {};
          for (const f of files) sizes[f] = (await stat(inside(dir, 'media', f))).size;
          send(200, sizes);
        }
        return true;
      }
      // POST /api/projects/:id/media?name=&alt=&width=&height= — raw body, content checked against
      // its Content-Type; images and SVGs carry dimensions measured by the browser.
      if (action === 'POST /media') {
        await readSite(id);
        const mime = (req.headers['content-type'] ?? '').split(';')[0]?.trim() ?? '';
        const type = MEDIA_TYPES[mime];
        if (!type) {
          throw new HttpError(415, msg('server.format'));
        }
        const content = await body(req, MAX_UPLOAD);
        if (content.length > type.max) throw new HttpError(413, msg('server.fileTooLarge'));
        if (type.kind === 'svg') {
          const reason = checkSvg(content.toString('utf8'));
          if (reason) throw new HttpError(415, msg('server.svg', { reason: msg(reason) }));
        } else if (!type.sniff(content)) {
          throw new HttpError(415, msg('server.sniff'));
        }
        const assetId = randomId('a', 10);
        const file = `${assetId}.${type.ext}`;
        const meta = {
          id: assetId,
          file,
          ...(cleanName(url.searchParams.get('name')) && { name: cleanName(url.searchParams.get('name')) }),
        };
        let asset: Asset;
        if (type.kind === 'file') {
          asset = { ...meta, kind: 'file', mime: mime as never, size: content.length };
        } else if (type.kind === 'font') {
          asset = {
            ...meta,
            kind: 'font',
            mime: 'font/woff2',
            size: content.length,
            ...guessFont(meta.name ?? file),
          };
        } else {
          // ponytail: dimensions measured by the browser; only used for width/height attributes.
          const width = Number(url.searchParams.get('width'));
          const height = Number(url.searchParams.get('height'));
          if (![width, height].every((n) => Number.isInteger(n) && n > 0 && n <= 20000)) {
            throw new HttpError(400, msg('server.dimensions'));
          }
          const alt = cleanName(url.searchParams.get('alt')).slice(0, 300);
          asset =
            type.kind === 'svg'
              ? { ...meta, kind: 'svg', mime: 'image/svg+xml', width, height, ...(alt && { alt }) }
              : { ...meta, kind: 'image', mime: mime as never, width, height, ...(alt && { alt }) };
        }
        await mkdir(join(dir, 'media'), { recursive: true });
        await atomicWrite(inside(dir, 'media', file), content);
        send(201, asset);
        return true;
      }
      // POST /api/projects/:id/export — body: the site as edited (saved or not); writes a standalone
      // Astro project under exportsDir.
      // Body: { site, build? }. Pre-export checks (SB-11) block on errors; with `build`, the static site is
      // also built (npm ci + astro build in the exported sources) and copied next to them (SB-10).
      if (action === 'POST /export') {
        await readSite(id);
        const input = (await jsonBody(req)) as { site?: unknown; build?: unknown };
        const present = new Set(await readdir(join(dir, 'media')).catch(() => []));
        const { site, checks } = checkSite(input.site, registry, present);
        if (!site || checks.some((c) => c.severity === 'error')) {
          throw new HttpError(422, msg('server.checks'), checks);
        }
        if (site.id !== id) throw new HttpError(400, msg('server.siteId'));
        const stamp = new Date().toISOString().replace(/[:.]/g, '-').slice(0, 19);
        const outDir = inside(options.exportsDir, `${id}-${stamp}`);
        const files = await exportProject(site, registry, outDir, { mediaDirs: [join(dir, 'media')] });
        let staticDir: string | undefined;
        if (input.build === true) {
          try {
            await run('npm', ['ci', '--no-audit', '--no-fund'], { cwd: outDir, timeout: 10 * 60_000 });
            await run('npm', ['run', 'build'], { cwd: outDir, timeout: 10 * 60_000 });
          } catch (e) {
            const err = e as { stderr?: string; message: string };
            throw new HttpError(
              500,
              msg('server.build', { detail: (err.stderr || err.message).slice(-600) }),
            );
          }
          staticDir = inside(options.exportsDir, `${id}-${stamp}-statique`);
          await cp(join(outDir, 'dist'), staticDir, { recursive: true });
        }
        // Names of the downloadable archives (GET /api/exports/:name.tar.gz).
        const download = (path?: string) => path?.slice(resolve(options.exportsDir).length + 1);
        send(201, {
          path: outDir,
          files: files.length,
          staticPath: staticDir,
          download: download(outDir),
          staticDownload: download(staticDir),
          checks,
        });
        return true;
      }
      // GET /api/projects/:id/archive — the source site and its media files, for archiving and re-import (SB-12).
      if (action === 'GET /archive') {
        res.writeHead(200, {
          'content-type': 'application/json; charset=utf-8',
          'content-disposition': `attachment; filename="${id}.ns-archive.json"`,
          'cache-control': 'no-store',
        });
        res.end(JSON.stringify(await archiveOf(id)));
        return true;
      }
      // POST /api/projects/:id/template { name, description } — saves the project as a site template.
      if (action === 'POST /template') {
        const input = (await jsonBody(req)) as { name?: unknown; description?: unknown };
        const name = typeof input.name === 'string' ? input.name.trim().slice(0, 200) : '';
        if (!name) throw new HttpError(400, msg('server.templateName'));
        const description =
          typeof input.description === 'string' ? input.description.trim().slice(0, 300) : '';
        const templateId = randomId('t', 10);
        await mkdir(userTemplates, { recursive: true });
        await atomicWrite(
          inside(userTemplates, `${templateId}.json`),
          JSON.stringify({ ...(await archiveOf(id)), template: { name, description } }),
        );
        send(201, { id: templateId });
        return true;
      }
    }

    throw new HttpError(404, msg('server.route'));
  }

  /** Connect-style middleware (Vite dev and preview servers, tests). */
  return (req: IncomingMessage, res: ServerResponse, next: () => void) => {
    handle(req, res)
      .then((handled) => handled || next())
      .catch((e: unknown) => {
        const status = e instanceof HttpError ? e.status : 500;
        if (status === 500) console.error(e);
        res.writeHead(status, { 'content-type': 'application/json; charset=utf-8' });
        res.end(
          JSON.stringify({
            error: e instanceof HttpError ? e.detail : msg('server.internal'),
            ...(e instanceof HttpError && e.details ? { diagnostics: e.details } : {}),
          }),
        );
      });
  };
}
